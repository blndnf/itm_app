# PDF mit Koordinaten extrahieren
function Get-PdfTextChunks {
    param($pdfPath)
    $reader = New-Object iTextSharp.text.pdf.PdfReader -ArgumentList $pdfPath
    $allChunks = @()
    
    for ($i = 1; $i -le $reader.NumberOfPages; $i++) {
        $strategy = New-Object CoordinateTextExtractionStrategy
        [void][iTextSharp.text.pdf.parser.PdfTextExtractor]::GetTextFromPage($reader, $i, $strategy)
        
        foreach ($chunk in $strategy.TextChunks) {
            $allChunks += [pscustomobject]@{
                Page = $i
                X = $chunk.X
                Y = $chunk.Y
                Text = $chunk.Text
            }
        }
    }
    
    $reader.Close()
    return $allChunks
}

# Gruppiere Chunks nach Y-Position (physische Zeilen)
function Group-ChunksByY {
    param($chunks, $yTolerance = 0.5)
    
    $yGroups = @{}
    
    foreach ($chunk in $chunks) {
        $y = $chunk.Y
        $foundGroup = $false
        
        # Suche existierende Y-Gruppe
        foreach ($existingY in $yGroups.Keys) {
            if ([Math]::Abs($y - $existingY) -lt $yTolerance) {
                $yGroups[$existingY] += $chunk
                $foundGroup = $true
                break
            }
        }
        
        # Neue Gruppe erstellen
        if (-not $foundGroup) {
            $yGroups[$y] = @($chunk)
        }
    }
    
    return $yGroups
}

# Retrospektive Footer-Bereinigung von Zelleninhalten
function Clean-FooterFromCell {
    param($cellText, $columnName)

    $cleaned = $cellText

    # User-Spalte: Entferne Footer-Datum am Ende (mit Trennzeichen)
    if ($columnName -eq "User") {
        # Entferne " ion Date : YYYY-MM-DD" (ion nicht Teil eines Wortes)
        $cleaned = $cleaned -replace "(?<!\w)ion\s+Date\s*:\s*\d{4}-\d{2}-\d{2}.*$", ""
        # Entferne " Date : YYYY-MM-DD" oder " Date:YYYY-MM-DD"
        $cleaned = $cleaned -replace "\s+Date\s*:\s*\d{4}-\d{2}-\d{2}.*$", ""
        # Fallback: Entferne Datum-Pattern am Ende (wenn durch Leerzeichen getrennt)
        $cleaned = $cleaned -replace "\s+\d{4}-\d{2}-\d{2}\s*$", ""
    }

    # Group-Spalte: Entferne Zeitstempel-Fragmente (HH:MM oder HH:MM:SS)
    if ($columnName -eq "Group") {
        $cleaned = $cleaned -replace "\s+\d{1,2}:\d{2}:\d{2}\s*$", ""
        $cleaned = $cleaned -replace "\s+\d{1,2}:\d{2}:\s*$", ""
        $cleaned = $cleaned -replace "\s+\d{1,2}:\d{2}\s*$", ""
    }

    # Time-Spalte: Entferne alles NACH dem ersten GMT±HH:MM
    if ($columnName -match "Time") {
        if ($cleaned -match "(.*?GMT[+-]\d{2}:\d{2})") {
            $cleaned = $matches[1]
        }
    }

    # Error-Spalte: Entferne "Page X/Y" (mit oder ohne Leerzeichen)
    if ($columnName -match "Error") {
        $cleaned = $cleaned -replace "Page\s*\d+/\d+", ""
        $cleaned = $cleaned -replace "^\s*\d+/\d+\s*$", ""
    }

    return $cleaned.Trim()
}

# Parse alle Eintraege
function Parse-AuditEntries {
    param($chunks, $pdfName)
    
    Write-Host ""
    Write-Host "=== PARSING STARTEN ==="
    Write-Host "Chunks gesamt: $($chunks.Count)"
    
    # 1. Finde Header-Zeile
    $yGroups = Group-ChunksByY -chunks $chunks
    $headerY = $null
    
    foreach ($y in ($yGroups.Keys | Sort-Object -Descending)) {
        $yChunks = $yGroups[$y]
        $yText = ($yChunks | Sort-Object X | Select-Object -ExpandProperty Text) -join " "
        
        if ($yText -match "User" -and $yText -match "Group" -and 
            $yText -match "Time" -and $yText -match "Category") {
            $headerY = $y
            Write-Host "Header gefunden bei Y=$([Math]::Round($headerY, 2))"
            break
        }
    }
    
    if (-not $headerY) {
        Write-Host "FEHLER: Kein Header gefunden!"
        return @()
    }
    
    # 2. Extrahiere Spalten-X-Positionen aus Header
    $headerChunks = $chunks | Where-Object { 
        [Math]::Abs($_.Y - $headerY) -lt 2.0 -and
        $_.Text -match "^(User|Group|Time|Succeeded|Category|Reason|Action|Error)"
    } | Sort-Object X
    
    if ($headerChunks.Count -lt 8) {
        Write-Host "FEHLER: Nur $($headerChunks.Count) Spalten gefunden!"
        return @()
    }
    
    $columns = @()
    foreach ($hc in $headerChunks) {
        $columns += [pscustomobject]@{ Name = $hc.Text; XStart = $hc.X; XEnd = 999 }
    }

    # Setze XEnd fuer jede Spalte (= Start der naechsten Spalte)
    for ($i = 0; $i -lt $columns.Count; $i++) {
        if ($i+1 -lt $columns.Count) {
            $columns[$i].XEnd = $columns[$i+1].XStart
        } else {
            $columns[$i].XEnd = 1000
        }
    }

    Write-Host "Spalten erkannt: $($columns.Count)"

    # 3. Finde Tabellenzeilen-Starts (wo User UND Group gleichzeitig gefuellt)
    $tableRowStarts = @()
    $userCol = $columns[0]
    $groupCol = $columns[1]

    foreach ($y in ($yGroups.Keys | Sort-Object -Descending)) {
        if ($y -ge ($headerY - 10)) { continue }  # Ueberspringe Header
        if ($y -lt -50) { continue }  # Ueberspringe Footer

        $yChunks = $yGroups[$y]

        # Pruefe ob User-Spalte gefuellt ist
        $userChunks = $yChunks | Where-Object { $_.X -ge $userCol.XStart -and $_.X -lt $userCol.XEnd }

        # Pruefe ob Group-Spalte gefuellt ist und "ICPMH" enthaelt
        $groupChunks = $yChunks | Where-Object { $_.X -ge $groupCol.XStart -and $_.X -lt $groupCol.XEnd }
        $groupText = ($groupChunks | Select-Object -ExpandProperty Text) -join ""

        if ($userChunks -and ($groupText -match "ICPMH")) {
            $tableRowStarts += $y
        }
    }
    
    $tableRowStarts = $tableRowStarts | Sort-Object -Descending
    Write-Host "Tabellenzeilen erkannt: $($tableRowStarts.Count)"
    
    if ($tableRowStarts.Count -eq 0) {
        Write-Host "FEHLER: Keine Tabellenzeilen gefunden!"
        return @()
    }
    
    # 4. Fuer jede Tabellenzeile: Extrahiere Zellen
    $entries = @()
    
    for ($i = 0; $i -lt $tableRowStarts.Count; $i++) {
        $rowStartY = $tableRowStarts[$i]
        $rowEndY = if ($i+1 -lt $tableRowStarts.Count) { $tableRowStarts[$i+1] } else { -100 }
        
        # Hole alle Chunks in diesem Y-Bereich
        $rowChunks = $chunks | Where-Object { $_.Y -le $rowStartY -and $_.Y -gt $rowEndY }
        
        $entry = [ordered]@{
            Page         = ($rowChunks | Select-Object -First 1).Page
            User         = ""
            Group        = ""
            Time         = ""
            Succeeded    = ""
            Category     = ""
            Reason       = ""
            Action       = ""
            ErrorMessage = ""
            SourcePDF    = $pdfName
        }
        
        # Extrahiere jede Spalte
        for ($c = 0; $c -lt $columns.Count; $c++) {
            $col = $columns[$c]

            # Finde Chunks in dieser Spalte (zwischen XStart und XEnd)
            $colChunks = $rowChunks | Where-Object {
                $_.X -ge $col.XStart -and $_.X -lt $col.XEnd
            } | Sort-Object @{Expression="Y"; Descending=$true}, X

            $cellText = ($colChunks | Select-Object -ExpandProperty Text) -join " "
            $cellText = $cellText.Trim()

            # RETROSPEKTIVE BEREINIGUNG: Nur bei der LETZTEN Tabellenzeile
            $finalCellText = $cellText
            if ($i -eq ($tableRowStarts.Count - 1)) {
                $finalCellText = Clean-FooterFromCell -cellText $cellText -columnName $col.Name
            }

            # Zuordnung nach Spaltenname
            if ($col.Name -eq "User") { $entry.User = $finalCellText }
            elseif ($col.Name -eq "Group") { $entry.Group = $finalCellText }
            elseif ($col.Name -match "Time") { $entry.Time = $finalCellText }
            elseif ($col.Name -eq "Succeeded") { $entry.Succeeded = $finalCellText }
            elseif ($col.Name -eq "Category") { $entry.Category = $finalCellText }
            elseif ($col.Name -eq "Reason") { $entry.Reason = $finalCellText }
            elseif ($col.Name -eq "Action") { $entry.Action = $finalCellText }
            elseif ($col.Name -match "Error") { $entry.ErrorMessage = $finalCellText }
        }
        
        $entries += [pscustomobject]$entry
    }
    
    return $entries
}

